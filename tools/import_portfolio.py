#!/usr/bin/env python3
"""
Import your design images into the portfolio (optional helper).

How to use (on your own computer):
  1. Download the "Nahid's Design" folder from Google Drive and put the
     image files into a folder called  portfolio-source/  next to index.html
  2. Install Pillow once:   pip install pillow
  3. Run from the project folder:   python tools/import_portfolio.py

What it does:
  - skips duplicate files (same picture, or the same name as .png and .jpg)
  - resizes each image to max 1080 px wide and saves a light JPG into
    assets/images/portfolio/design-01.jpg, design-02.jpg, ...
  - writes a fresh portfolio-data.js listing every image as a
    "Sample Project" in "Social Media Designs"

After running, open portfolio-data.js and edit titles, categories and
descriptions. Do not run it again afterwards, or it will overwrite your edits.
"""
import hashlib
import json
import re
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is missing. Install it with:  pip install pillow")

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "portfolio-source"
OUT_DIR = ROOT / "assets" / "images" / "portfolio"
DATA_FILE = ROOT / "portfolio-data.js"
MAX_WIDTH = 1080

if not SOURCE.is_dir():
    sys.exit("Folder not found: " + str(SOURCE) + "\nCreate it and put your design images inside.")

files = [p for p in SOURCE.iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png", ".webp"}]
# Natural sort so "design (2)" comes before "design (10)"
files.sort(key=lambda p: [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", p.stem)])

seen_hashes, seen_stems, unique = set(), set(), []
for p in files:
    digest = hashlib.md5(p.read_bytes()).hexdigest()
    stem = p.stem.lower()
    if digest in seen_hashes or stem in seen_stems:
        print("skip duplicate:", p.name)
        continue
    seen_hashes.add(digest)
    seen_stems.add(stem)
    unique.append(p)

OUT_DIR.mkdir(parents=True, exist_ok=True)
entries = []
for n, p in enumerate(unique, start=1):
    name = "design-%02d.jpg" % n
    img = Image.open(p).convert("RGB")
    if img.width > MAX_WIDTH:
        img = img.resize((MAX_WIDTH, round(img.height * MAX_WIDTH / img.width)), Image.LANCZOS)
    img.save(OUT_DIR / name, "JPEG", quality=82, optimize=True)
    entries.append({
        "title": "Social Media Design %02d" % n,
        "category": "Social Media Designs",
        "image": "assets/images/portfolio/" + name,
        "alt": "Social media design %02d" % n,
        "description": "A social media design.",
        "label": "Sample Project",
        "url": "",
    })
    print("saved", name, "<-", p.name)

header = (
    "/* PORTFOLIO DATA - generated by tools/import_portfolio.py.\n"
    "   Edit titles, categories, descriptions and labels below.\n"
    "   label: use \"Sample Project\" for self-created work, \"Client Project\" only for real client work.\n"
    "   category: e.g. \"Social Media Designs\", \"Carousel Posts\", \"Reels\", \"Content Calendars\", \"Instagram Feed\" */\n\n"
)
DATA_FILE.write_text(header + "window.PORTFOLIO_ITEMS = " + json.dumps(entries, indent=2) + ";\n", encoding="utf-8")
print("\nDone:", len(entries), "projects written to", DATA_FILE.name)
